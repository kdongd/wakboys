create table member (
    id            bigint generated by default as identity primary key,
    slug          varchar(40)  not null unique,
    name          varchar(20)  not null,
    theme_color   varchar(9)   not null,
    sort_order    int          not null,
    kakao_id      bigint unique,
    invite_code   varchar(20) unique,
    is_admin      boolean      not null default false,
    is_treasurer  boolean      not null default false,
    birth_month   int,
    birth_day     int,
    linked_at     timestamptz
);

create table refresh_token (
    id          bigint generated by default as identity primary key,
    member_id   bigint      not null references member (id) on delete cascade,
    token_hash  varchar(64) not null unique,
    expires_at  timestamptz not null,
    created_at  timestamptz not null default now()
);

create table dues_config (
    id               int primary key,
    monthly_amount   int          not null,
    initial_balance  bigint       not null,
    bank_info        varchar(100),
    start_ym         varchar(7)   not null
);

create table dues_payment (
    id          bigint generated by default as identity primary key,
    member_id   bigint      not null references member (id),
    ym          varchar(7)  not null,
    amount      int         not null,
    checked_by  bigint references member (id),
    checked_at  timestamptz not null,
    unique (member_id, ym)
);

create table dues_expense (
    id          bigint generated by default as identity primary key,
    title       varchar(100) not null,
    amount      int          not null,
    spent_on    date         not null,
    created_by  bigint references member (id),
    created_at  timestamptz  not null
);

create table trip (
    id                  bigint generated by default as identity primary key,
    year                int          not null,
    season              varchar(10)  not null,
    title               varchar(60)  not null,
    destination         varchar(60),
    start_date          date,
    end_date            date,
    settle_receiver_id  bigint references member (id),
    created_by          bigint references member (id),
    created_at          timestamptz  not null,
    unique (year, season)
);

create table poll (
    id          bigint generated by default as identity primary key,
    trip_id     bigint       not null references trip (id) on delete cascade,
    category    varchar(20)  not null,
    question    varchar(100) not null,
    multiple    boolean      not null default false,
    closes_at   timestamptz,
    closed      boolean      not null default false,
    created_by  bigint references member (id),
    created_at  timestamptz  not null
);

create table poll_option (
    id          bigint generated by default as identity primary key,
    poll_id     bigint       not null references poll (id) on delete cascade,
    label       varchar(100) not null,
    sort        int          not null default 0,
    created_by  bigint references member (id)
);

create table poll_vote (
    id          bigint generated by default as identity primary key,
    poll_id     bigint      not null references poll (id) on delete cascade,
    option_id   bigint      not null references poll_option (id) on delete cascade,
    member_id   bigint      not null references member (id),
    created_at  timestamptz not null,
    unique (option_id, member_id)
);

create table itinerary_item (
    id          bigint generated by default as identity primary key,
    trip_id     bigint       not null references trip (id) on delete cascade,
    day_no      int          not null,
    start_time  varchar(5),
    title       varchar(100) not null,
    memo        varchar(500),
    sort        int          not null default 0,
    created_by  bigint references member (id),
    created_at  timestamptz  not null
);

create table place (
    id          bigint generated by default as identity primary key,
    trip_id     bigint       not null references trip (id) on delete cascade,
    name        varchar(100) not null,
    category    varchar(20)  not null,
    address     varchar(200),
    url         varchar(500),
    memo        varchar(500),
    lat         double precision,
    lng         double precision,
    visited     boolean      not null default false,
    created_by  bigint references member (id),
    created_at  timestamptz  not null
);

create table checklist_item (
    id           bigint generated by default as identity primary key,
    trip_id      bigint       not null references trip (id) on delete cascade,
    title        varchar(100) not null,
    kind         varchar(10)  not null,
    assignee_id  bigint references member (id),
    done         boolean      not null default false,
    done_by      bigint references member (id),
    done_at      timestamptz,
    created_by   bigint references member (id),
    created_at   timestamptz  not null
);

create table checklist_check (
    id         bigint generated by default as identity primary key,
    item_id    bigint not null references checklist_item (id) on delete cascade,
    member_id  bigint not null references member (id),
    unique (item_id, member_id)
);

create table trip_expense (
    id          bigint generated by default as identity primary key,
    trip_id     bigint       not null references trip (id) on delete cascade,
    title       varchar(100) not null,
    amount      int          not null,
    paid_by     bigint       not null references member (id),
    created_by  bigint references member (id),
    created_at  timestamptz  not null
);

create table settlement_transfer (
    id              bigint generated by default as identity primary key,
    trip_id         bigint      not null references trip (id) on delete cascade,
    from_member_id  bigint      not null references member (id),
    to_member_id    bigint      not null references member (id),
    amount          int         not null,
    sent_at         timestamptz not null,
    unique (trip_id, from_member_id, to_member_id)
);

create table post (
    id          bigint generated by default as identity primary key,
    author_id   bigint      not null references member (id),
    body        text        not null,
    created_at  timestamptz not null,
    updated_at  timestamptz not null
);

create table media (
    id            bigint generated by default as identity primary key,
    trip_id       bigint references trip (id) on delete cascade,
    post_id       bigint references post (id) on delete cascade,
    uploader_id   bigint       not null references member (id),
    object_key    varchar(200) not null,
    thumb_key     varchar(200),
    content_type  varchar(100) not null,
    kind          varchar(10)  not null,
    width         int,
    height        int,
    size_bytes    bigint,
    duration_sec  int,
    created_at    timestamptz  not null
);
create index idx_media_trip on media (trip_id, id desc);
create index idx_media_post on media (post_id);

create table comment (
    id           bigint generated by default as identity primary key,
    target_type  varchar(10)   not null,
    target_id    bigint        not null,
    author_id    bigint        not null references member (id),
    body         varchar(1000) not null,
    created_at   timestamptz   not null
);
create index idx_comment_target on comment (target_type, target_id);

create table reaction (
    id           bigint generated by default as identity primary key,
    target_type  varchar(10) not null,
    target_id    bigint      not null,
    member_id    bigint      not null references member (id),
    reaction     varchar(20) not null,
    created_at   timestamptz not null,
    unique (target_type, target_id, member_id)
);

create table push_subscription (
    id          bigint generated by default as identity primary key,
    member_id   bigint        not null references member (id) on delete cascade,
    endpoint    varchar(1000) not null unique,
    p256dh      varchar(200)  not null,
    auth        varchar(100)  not null,
    created_at  timestamptz   not null
);
